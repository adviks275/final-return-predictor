"""
Out-of-sample check: are the simulated 1-year return ranges honest?

Walks forward through a stock's history. At each checkpoint (every quarter):
  1. Fit the HMM using only the previous 5 years of returns (nothing after the checkpoint).
  2. Simulate 1,000 one-year paths starting from the regime the model sees on that date.
  3. Look up what the stock actually returned over the next year, and where that
     return fell inside the simulated distribution (its percentile).

If the model's ranges are honest, the actual return lands below the simulated
5th percentile about 5% of the time, above the 95th about 5% of the time, and
the percentiles are spread evenly between 0 and 100.

Run:  python calibration_check.py FTAI SPY
      python calibration_check.py --synthetic      (offline test of the pipeline)
"""
import argparse

import matplotlib.pyplot as plt
import numpy as np

from regime_model import fit_regimes

WINDOW = 252 * 5   # fit on the previous 5 years
HORIZON = 252      # predict 1 year ahead
STEP = 63          # one checkpoint per quarter
N_PATHS = 1000


def simulate_final_returns(mean, vol, trans, start_regime, rng, n_paths=N_PATHS, n_days=HORIZON):
    """Vectorized version of the main model's simulator: all paths at once."""
    regime = np.full(n_paths, start_regime)
    log_growth = np.zeros(n_paths)
    for _ in range(n_days):
        switch = rng.random(n_paths) < trans[regime, 1 - regime]
        regime = np.where(switch, 1 - regime, regime)
        log_growth += np.log1p(rng.normal(mean[regime], vol[regime]))
    return np.expm1(log_growth)


def walk_forward(returns, rng):
    pits = []
    for cut in range(WINDOW, len(returns) - HORIZON + 1, STEP):
        mean, vol, trans, gamma = fit_regimes(returns[cut - WINDOW:cut])
        sims = simulate_final_returns(mean, vol, trans, int(gamma[-1, 1] > 0.5), rng)
        actual = np.prod(1 + returns[cut:cut + HORIZON]) - 1
        pits.append(np.mean(sims < actual))
    return np.array(pits)


def load_returns(ticker):
    import yfinance as yf
    data = yf.download(ticker, period="max", auto_adjust=True, progress=False)
    close = data["Close"]
    if hasattr(close, "columns"):
        close = close.iloc[:, 0]
    return close.dropna().pct_change().dropna().values


def synthetic_returns(rng, n=252 * 20):
    """Returns generated by the model itself, so it should pass this check."""
    mean, vol = np.array([0.0005, -0.0005]), np.array([0.009, 0.025])
    trans = np.array([[0.98, 0.02], [0.05, 0.95]])
    reg = np.zeros(n, dtype=int)
    for t in range(1, n):
        reg[t] = rng.choice(2, p=trans[reg[t - 1]])
    return rng.normal(mean[reg], vol[reg])


def report(name, pits):
    below, above = np.mean(pits < 0.05), np.mean(pits > 0.95)
    print(f"\n{name}: {len(pits)} quarterly checkpoints (overlapping 1-year windows)")
    print(f"  Actual return below simulated 5th percentile:  {below:6.1%}   (honest model: ~5%)")
    print(f"  Actual return above simulated 95th percentile: {above:6.1%}   (honest model: ~5%)")
    print(f"  Inside the 90% range:                          {1 - below - above:6.1%}   (honest model: ~90%)")
    print(f"  Average percentile of actual return:           {pits.mean():6.1%}   (honest model: ~50%)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tickers", nargs="*", default=["FTAI", "SPY"])
    ap.add_argument("--synthetic", action="store_true")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)

    sets = {"synthetic": synthetic_returns(rng)} if a.synthetic else {t: load_returns(t) for t in a.tickers}
    fig, axes = plt.subplots(1, len(sets), figsize=(5.5 * len(sets), 4), squeeze=False)
    for ax, (name, rets) in zip(axes[0], sets.items()):
        if len(rets) < WINDOW + HORIZON:
            print(f"\n{name}: only {len(rets)} days of history, need {WINDOW + HORIZON}. Skipped.")
            continue
        pits = walk_forward(rets, rng)
        report(name, pits)
        ax.hist(pits * 100, bins=10, range=(0, 100), color="steelblue", edgecolor="white")
        ax.axhline(len(pits) / 10, color="black", linestyle="--", label="honest model")
        ax.set_title(f"{name}: where the actual 1-year return fell")
        ax.set_xlabel("Percentile within simulated distribution")
        ax.set_ylabel("Checkpoints")
        ax.legend()
    plt.tight_layout()
    plt.savefig("calibration.png", dpi=150)
    print("\nSaved plot to calibration.png")
    print("Note: checkpoints are a quarter apart but each looks a year ahead, so neighbours overlap "
          "and aren't independent. Treat the percentages as rough.")


if __name__ == "__main__":
    main()
